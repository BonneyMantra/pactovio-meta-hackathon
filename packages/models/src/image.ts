import { b64ToBytes, bytesToB64, metaFetch, metered, type MetaEnv } from './meta-http';

export const IMAGE_MODEL = 'muse-image-1.0';
/** Muse Image list price: flat $0.01 per generated image. */
export const IMAGE_USD = 0.01;

export interface GeneratedImage { bytes: Uint8Array; mime: string; model: string; ms: number; costUsd: number }
export interface ImageOpts { prompt: string; size?: string; format?: 'png' | 'jpeg' | 'webp'; fast?: boolean; fetchImpl?: typeof fetch }

const MIME = { png: 'image/png', jpeg: 'image/jpeg', webp: 'image/webp' } as const;

async function call(env: MetaEnv, path: string, body: Record<string, unknown>, o: ImageOpts): Promise<GeneratedImage> {
  const t0 = Date.now();
  const format = o.format ?? 'jpeg';
  const full = { model: IMAGE_MODEL, n: 1, response_format: 'b64_json', output_format: format, reasoning_strength: o.fast ? 'low' : 'high', ...(o.size ? { size: o.size } : {}), ...body };
  const json = await metered(env, IMAGE_USD, async () => {
    const res = await metaFetch(env, { path, fetchImpl: o.fetchImpl, init: { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(full) } });
    return await res.json() as { data?: { b64_json?: string; url?: string }[] };
  });
  const item = json.data?.[0];
  let bytes: Uint8Array | null = item?.b64_json ? b64ToBytes(item.b64_json) : null;
  if (!bytes && item?.url) bytes = new Uint8Array(await (await (o.fetchImpl ?? fetch)(item.url)).arrayBuffer());
  if (!bytes?.length) throw new Error('Muse Image returned no image');
  return { bytes, mime: MIME[format], model: `meta:${IMAGE_MODEL}`, ms: Date.now() - t0, costUsd: IMAGE_USD };
}

/** Text-to-image through /v1/images/generations. */
export const generateImage = (env: MetaEnv, o: ImageOpts) => call(env, '/images/generations', { prompt: o.prompt }, o);

/** Edit an image through /v1/images/edits (JSON body with `images`). */
export const editImage = (env: MetaEnv, o: ImageOpts & { image: { bytes: Uint8Array; mime: string } }) =>
  call(env, '/images/edits', { prompt: o.prompt, images: [{ image_url: `data:${o.image.mime};base64,${bytesToB64(o.image.bytes)}` }] }, o);

/** Persist generated bytes to R2 and return the key (the caller serves it through an authenticated route). */
export async function storeImage(bucket: R2Bucket, key: string, img: Pick<GeneratedImage, 'bytes' | 'mime'>): Promise<string> {
  await bucket.put(key, img.bytes, { httpMetadata: { contentType: img.mime } });
  return key;
}
